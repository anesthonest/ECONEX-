export function normalizeRoutePath(rawPath: string): string {
  const withoutQuery = rawPath.split('?')[0].split('#')[0].trim();
  if (!withoutQuery || withoutQuery === '/') return '/';
  return withoutQuery.endsWith('/') ? withoutQuery.slice(0, -1) : withoutQuery;
}

export function getNavItemById(id: string): V18NavItem | undefined {
  return NAVIGATION_REGISTRY.find((item) => item.id === id);
}

export function resolveRouteToNavItem(pathname: string): {
  item: V18NavItem | null;
  isUnknown: boolean;
  normalizedPath: string;
} {
  const normalized = normalizeRoutePath(pathname);
  const direct = NAVIGATION_REGISTRY.find(
    (item) => item.route === normalized || item.legacyRoutes?.includes(normalized)
  );
  if (direct) {
    return { item: direct, isUnknown: false, normalizedPath: normalized };
  }
  return { item: null, isUnknown: true, normalizedPath: normalized };
}

export function hasRolePermission(item: V18NavItem, role: UserRole): boolean {
  return item.requiredRoles.includes(role);
}

export function meetsExperienceMode(item: V18NavItem, mode: ExperienceModeLevel): boolean {
  return EXPERIENCE_RANK[mode] >= EXPERIENCE_RANK[item.minExperienceMode];
}

export function canAccessNavItem(
  item: V18NavItem,
  role: UserRole,
  mode: ExperienceModeLevel
): boolean {
  return hasRolePermission(item, role) && meetsExperienceMode(item, mode);
}

export function getAuthorizedNavGroups(
  role: UserRole,
  mode: ExperienceModeLevel,
  includeAllPermittedForRole = false
): { groupId: V18NavGroupId; groupLabel: string; items: V18NavItem[] }[] {
  const accessible = NAVIGATION_REGISTRY.filter((item) =>
    includeAllPermittedForRole
      ? hasRolePermission(item, role)
      : canAccessNavItem(item, role, mode)
  );

  return GROUP_ORDER.map((group) => ({
    groupId: group.id,
    groupLabel: group.label,
    items: accessible.filter((item) => item.groupId === group.id),
  })).filter((g) => g.items.length > 0);
}

export function getBreadcrumbsForNavItem(itemId: string): V18BreadcrumbItem[] {
  const item = getNavItemById(itemId);
  if (!item) return [{ id: 'home', label: 'Home', route: '/home' }];

  const trail: V18BreadcrumbItem[] = [];
  const visited = new Set<string>();
  let current: V18NavItem | undefined = item;
  while (current && !visited.has(current.id)) {
    visited.add(current.id);
    trail.unshift({ id: current.id, label: current.label, route: current.route });
    current = current.parentId ? getNavItemById(current.parentId) : undefined;
  }
  if (trail[0]?.id !== 'home') {
    trail.unshift({ id: 'home', label: 'Home', route: '/home' });
  }
  return trail;
}

export function searchNavRegistry(
  query: string,
  role: UserRole,
  mode: ExperienceModeLevel,
  limit = 12
): V18NavItem[] {
  const clean = query.trim().toLowerCase();
  const candidates = NAVIGATION_REGISTRY.filter((item) => hasRolePermission(item, role));
  if (!clean) {
    return candidates
      .filter((item) => meetsExperienceMode(item, mode))
      .slice(0, limit);
  }
  return candidates
    .map((item) => {
      const hay = `${item.label} ${item.description} ${item.route} ${item.groupLabel} ${item.keywords.join(' ')}`.toLowerCase();
      let score = 0;
      if (item.label.toLowerCase().startsWith(clean)) score += 6;
      else if (item.label.toLowerCase().includes(clean)) score += 4;
      if (item.keywords.some((k) => k.toLowerCase().includes(clean))) score += 3;
      if (hay.includes(clean)) score += 1;
      if (meetsExperienceMode(item, mode)) score += 1;
      return { item, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.item);
}
