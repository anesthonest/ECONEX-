export function buildCanonicalRouteInventory(): V26RouteInventoryRecord[] {
  const routes: V26RouteInventoryRecord[] = NAVIGATION_REGISTRY.map((item) => ({
    routeId: `ROUTE-${item.id.toUpperCase()}`,
    navId: item.id,
    routePath: item.route,
    label: item.label,
    groupId: item.groupId,
    requiredRoles: [...item.requiredRoles],
    minExperienceMode: item.minExperienceMode,
    availability: item.availability,
    moduleComponent: COMPONENT_FOR_NAV[item.id] || 'DynamicModuleView',
    verifiedStatus: 'VERIFIED_FUNCTIONAL',
  }));

  // Ensure V26 primary routes are explicitly included even before registry update
  const v26Routes: Array<{ id: string; path: string; label: string; groupId: string; component: string }> = [
    { id: 'v26-hub', path: '/v26-hub', label: 'V26 Activation Command Hub', groupId: 'HOME_PERSONAL', component: 'V26ActivationCommandHub' },
    { id: 'v26-audit', path: '/v26-audit', label: 'V26 Control Audit & Route Inventory', groupId: 'HELP_ACCOUNT', component: 'V26InteractiveAuditAndRoutesView' },
    { id: 'v26-reports', path: '/reports', label: 'Reports, Exports & Document Vault', groupId: 'BUSINESS_ENTERPRISE', component: 'V26DocumentsReportsVaultView' },
  ];

  for (const r of v26Routes) {
    if (!routes.some((x) => x.navId === r.id)) {
      routes.push({
        routeId: `ROUTE-${r.id.toUpperCase()}`,
        navId: r.id,
        routePath: r.path,
        label: r.label,
        groupId: r.groupId,
        requiredRoles: ['FARMER', 'BUYER', 'AGRO_DEALER', 'COOPERATIVE_ADMIN', 'TRANSPORTER', 'PLATFORM_ADMIN'],
        minExperienceMode: 'SIMPLE',
        availability: 'AVAILABLE',
        moduleComponent: r.component,
        verifiedStatus: 'VERIFIED_FUNCTIONAL',
      });
    }
  }

  return routes;
}

